import p from 'puppeteer-core';
const base = process.argv[2] || 'http://localhost:8788';
const b = await p.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const pg = await b.newPage(); await pg.setViewport({ width: 430, height: 900 });
const errs = []; pg.on('pageerror', e => errs.push(e.message)); pg.on('console', m => m.type() === 'error' && errs.push(m.text()));
await pg.goto(base + '/#home'); 
const [fc] = await Promise.all([pg.waitForFileChooser(), pg.click('a.big-choice.snap')]);
await fc.accept([process.argv[3] || '/tmp/fake.jpg']);
await pg.waitForSelector('#goRecipes', { timeout: 90000 });
await pg.screenshot({ path: '/tmp/s-scan.png' });
console.log('scan:', await pg.$eval('#scanBody h2', e => e.textContent), await pg.$$eval('#scanBody .chip[data-rmi]', a => a.map(x => x.textContent).join(' | ')));
await pg.click('#goRecipes'); await pg.waitForFunction(() => document.querySelector('#recipesBody h3'), { timeout: 90000 });
await pg.screenshot({ path: '/tmp/s-recipes.png' });
console.log('recipes:', await pg.$$eval('#recipesBody b', a => a.map(x => x.textContent).join(' | ')));
await pg.click('[data-rec^="more:0"]'); await pg.waitForSelector('#recipeBody .steps');
await pg.screenshot({ path: '/tmp/s-recipe.png', fullPage: false });
console.log('steps:', await pg.$$eval('#recipeBody .steps li', a => a.length));
await pg.click('#recipeBody [data-addmiss="cur"]'); await new Promise(r => setTimeout(r, 500));
console.log('list:', await pg.$eval('#listCount', e => e.textContent), await pg.$eval('#listTotal', e => e.textContent));
await pg.screenshot({ path: '/tmp/s-list.png' });
await pg.goto(base + '/#crave'); await pg.type('#craveInput', 'chicken tikka masala'); await pg.click('#craveGo');
await pg.waitForSelector('#compareBody .verdict', { timeout: 90000 }); await pg.screenshot({ path: '/tmp/s-compare.png' });
console.log('compare:', await pg.$eval('#compareBody .verdict', e => e.innerText.replace(/\n/g, ' ')));
await pg.reload(); await pg.goto(base + '/#list'); console.log('persisted:', await pg.$eval('#listCount', e => e.textContent));
console.log('errors:', errs.join(' ; ') || 'none'); await b.close();
